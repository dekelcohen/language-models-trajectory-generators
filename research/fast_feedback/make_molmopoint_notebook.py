"""Build molmopoint4b_vid_kaggle.ipynb: MolmoPoint-Vid-4B VQA (same CASES as EmbeddingGemma 2) + pointing.

Cases/texts, image hosting and the VQA prompt/parse/score helpers come from common.py.

    python research/fast_feedback/make_molmopoint_notebook.py
"""
from pathlib import Path

from common import (code, gpu_info_cell, hf_login_cell, images_cells, inline_source, label_token_ids, md,
                    option_probs, parse_vqa_answer, resolve_images, vqa_question, vqa_scores, write_notebook)

OUT = Path(__file__).with_name("molmopoint4b_vid_kaggle.ipynb")
MODEL_ID = "allenai/MolmoPoint-Vid-4B"


def main():
    images = resolve_images()
    cells = [
        md(f"# MolmoPoint-Vid-4B - VQA + pointing on sim frames\n"
           f"Kaggle, GPU T4 x2. Loads `{MODEL_ID}` (Qwen3-4B + SigLIP, `trust_remote_code`, "
           "transformers 4.57.1 per the model card) and asks multiple-choice / yes-no questions built from the "
           "same cases as the EmbeddingGemma 2 notebook, then asks it to point to the door handle.\n\n"
           "Notes:\n"
           "- The checkpoint is stored in float32 (4.86B params, ~19.5 GB). T4 has no bfloat16 (the card uses "
           "bf16 autocast), so the default here is **fp32 split over both T4s** with `device_map='auto'`. "
           "`DTYPE='fp16'` (~9.7 GB) is faster but untested by Ai2 and may overflow.\n"
           "- T4 is sm75: no FlashAttention 2, so `attn_implementation='sdpa'`.\n"
           "- This checkpoint is trained for *video pointing* only; `allenai/MolmoPoint-8B` is the generalist "
           "(set `MODEL_ID`, needs fp16 or ~35 GB fp32 - does not fit 2xT4 in fp32).\n\n"
           "Generated by `make_molmopoint_notebook.py`."),
        code("!pip install -q transformers==4.57.1 accelerate einops decord2"),
        gpu_info_cell(", transformers\nprint('transformers', transformers.__version__)"),
        md("Optional: if the HF download needs auth, add a Kaggle secret `HF_TOKEN`."),
        hf_login_cell(),
        *images_cells(images),
        md("## VQA helpers (from common.py)"),
        code(inline_source(vqa_question, parse_vqa_answer, label_token_ids, option_probs, vqa_scores)),
        md("## Load model"),
        code("import time\n"
             "from transformers import AutoModelForImageTextToText, AutoProcessor\n\n"
             f"MODEL_ID = '{MODEL_ID}'\n"
             "DTYPE = 'fp32'  # 'fp32' (2 GPUs, safe) or 'fp16' (1 GPU, faster, may overflow); T4 has no bf16\n"
             "dtype = torch.float32 if DTYPE == 'fp32' else torch.float16\n"
             "n_gpu = torch.cuda.device_count()\n"
             "max_memory = {i: '14GiB' for i in range(n_gpu)} if DTYPE == 'fp32' else None\n\n"
             "t0 = time.time()\n"
             "model = AutoModelForImageTextToText.from_pretrained(\n"
             "    MODEL_ID, trust_remote_code=True, dtype=dtype,\n"
             "    device_map='auto', max_memory=max_memory,\n"
             "    attn_implementation='sdpa',  # T4 (sm75): no FlashAttention 2\n"
             ")\n"
             "model.eval()\n"
             "processor = AutoProcessor.from_pretrained(MODEL_ID, trust_remote_code=True, padding_side='left')\n"
             "n = sum(p.numel() for p in model.parameters())\n"
             "print(f'loaded {MODEL_ID} in {time.time()-t0:.1f}s, {n/1e9:.2f}B params, dtype {dtype}')\n"
             "for i in range(n_gpu):\n"
             "    print(f'  cuda:{i}: {torch.cuda.memory_allocated(i)/2**30:.2f} GB allocated')\n"
             "print('device map:', sorted(set(map(str, getattr(model, 'hf_device_map', {}).values()))))"),
        md("## Generation helper\n"
           "Greedy decoding with the MolmoPoint logit processor (keeps point tokens valid). "
           "`output_logits=True` returns the raw first-step logits used for option probabilities."),
        code("def run(image_path, prompt, max_new_tokens=32, pointing=False):\n"
             "    msgs = [{'role': 'user', 'content': [\n"
             "        {'type': 'text', 'text': prompt},\n"
             "        {'type': 'image', 'image': Image.open(image_path).convert('RGB')}]}]\n"
             "    inputs = processor.apply_chat_template(\n"
             "        msgs, tokenize=True, add_generation_prompt=True, return_tensors='pt',\n"
             "        return_dict=True, padding=True, return_pointing_metadata=pointing)\n"
             "    metadata = inputs.pop('metadata', None)\n"
             "    inputs = {k: v.to(model.device) for k, v in inputs.items()}\n"
             "    with torch.inference_mode():\n"
             "        out = model.generate(**inputs, logits_processor=model.build_logit_processor_from_inputs(inputs),\n"
             "                             max_new_tokens=max_new_tokens, do_sample=False,\n"
             "                             output_logits=True, return_dict_in_generate=True)\n"
             "    gen = out.sequences[:, inputs['input_ids'].size(1):]\n"
             "    text = processor.post_process_image_text_to_text(\n"
             "        gen, skip_special_tokens=not pointing, clean_up_tokenization_spaces=False)[0]\n"
             "    return text, out.logits[0][0], metadata"),
        md("## VQA per image\n"
           "Multiple-choice cases list the candidate texts as lettered options (answer = letter); single-text "
           "cases ask yes/no. Scores passed to `report()` are the option probabilities from the first "
           "generated token when it is an option token, else 1/0 for the parsed answer."),
        code("results = {}\n"
             "for im in IMAGES:\n"
             "    prompt, labels = vqa_question(im['texts'])\n"
             "    t0 = time.time()\n"
             "    answer, first_logits, _ = run(im['path'], prompt)\n"
             "    label, chosen = parse_vqa_answer(answer, im['texts'])\n"
             "    probs = option_probs(first_logits, label_token_ids(processor.tokenizer, labels))\n"
             "    print(f\"\\n=== {im['name']} ({time.time()-t0:.1f}s)\\n{prompt}\")\n"
             "    print(f'raw answer: {answer!r} -> label {label!r}, chosen {chosen!r}, probs {probs}')\n"
             "    if label is None and probs is None:\n"
             "        print('  could not parse the answer; scoring all options 0')\n"
             "    results[im['name']] = report(im['name'], im['texts'], im['expected'],\n"
             "                                 vqa_scores(im['texts'], label, probs))\n"
             "summarize(results)"),
        md("## Optional: point to the door handle\n"
           "MolmoPoint emits special `<POINT_..>` tokens; `model.extract_image_points` decodes them with the "
           "processor's pointing metadata into `(object_id, image_num, x, y)` in original image pixels."),
        code("import numpy as np\n"
             "POINT_PROMPT = 'Point to the door handle'\n"
             "fig, axs = plt.subplots(1, len(IMAGES), figsize=(4 * len(IMAGES), 4))\n"
             "for ax, im in zip(axs, IMAGES):\n"
             "    ax.imshow(Image.open(im['path']).convert('RGB')); ax.axis('off')\n"
             "    try:\n"
             "        text, _, md_ = run(im['path'], POINT_PROMPT, max_new_tokens=200, pointing=True)\n"
             "    except Exception as e:\n"
             "        print(f\"{im['name']}: generation failed: {type(e).__name__}: {e}\")\n"
             "        ax.set_title(im['name'] + '\\n(error)', fontsize=7); continue\n"
             "    try:\n"
             "        pts = np.array(model.extract_image_points(\n"
             "            text, md_['token_pooling'], md_['subpatch_mapping'], md_['image_sizes']), dtype=float).reshape(-1, 4)\n"
             "    except Exception as e:\n"
             "        print(f\"{im['name']}: point parse failed ({type(e).__name__}: {e}); raw: {text!r}\")\n"
             "        pts = np.zeros((0, 4))\n"
             "    print(f\"{im['name']}: {len(pts)} point(s) {pts[:, 2:].round(1).tolist()}\")\n"
             "    if not len(pts):\n"
             "        print(f'  raw: {text!r}')\n"
             "    ax.scatter(pts[:, 2], pts[:, 3], s=80, c='red', marker='x')\n"
             "    ax.set_title(f\"{im['name']}\\n{len(pts)} point(s)\", fontsize=7)\n"
             "plt.show()"),
    ]
    write_notebook(OUT, cells)
    print(f"{sum(1 for i in images if i['url'])}/{len(images)} images via imgbb URL")


if __name__ == "__main__":
    main()
