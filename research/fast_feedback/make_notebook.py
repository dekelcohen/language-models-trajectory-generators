"""Build embeddinggemma2_kaggle.ipynb: EmbeddingGemma 2 image<->text similarity on sim frames.

Cases/texts and image hosting (imgbb URLs, base64 fallback) come from common.py.

    python research/fast_feedback/make_notebook.py
"""
from pathlib import Path

from common import code, gpu_info_cell, hf_login_cell, images_cells, md, resolve_images, write_notebook

OUT = Path(__file__).with_name("embeddinggemma2_kaggle.ipynb")


def main():
    images = resolve_images()
    cells = [
        md("# EmbeddingGemma 2 - sim frame vs. text similarity\n"
           "Kaggle, GPU T4 x2. Loads `google/embeddinggemma-2` (text + vision encoders, audio skipped) "
           "and scores sim camera frames against short text descriptions.\n\n"
           "T4 has no bfloat16 and the model card forbids float16 (NaNs), so it runs in **float32** on "
           "`cuda:0` (~440M params, ~2 GB; the second T4 is not needed). Generated by `make_notebook.py`."),
        code("!pip install -q -U sentence-transformers transformers"),
        gpu_info_cell(", transformers, sentence_transformers\n"
                      "print('transformers', transformers.__version__, '| sentence-transformers', sentence_transformers.__version__)"),
        md("Optional: if the HF download needs auth, add a Kaggle secret `HF_TOKEN`."),
        hf_login_cell(),
        *images_cells(images),
        md("## Load model"),
        code("import time\n"
             "from sentence_transformers import SentenceTransformer\n\n"
             "t0 = time.time()\n"
             "model = SentenceTransformer(\n"
             "    'google/embeddinggemma-2',\n"
             "    device='cuda:0',\n"
             "    model_kwargs={'torch_dtype': torch.float32},  # no bf16 on T4; fp16 -> NaN\n"
             "    config_kwargs={'audio_config': None},         # text + image only\n"
             ")\n"
             "model.eval()\n"
             "n = sum(p.numel() for p in model.parameters())\n"
             "print(f'loaded in {time.time()-t0:.1f}s, {n/1e6:.0f}M params,',\n"
             "      f'{torch.cuda.memory_allocated(0)/2**30:.2f} GB on cuda:0, prompts: {list(model.prompts)}')"),
        md("## Image vs. text similarity\n"
           "Text is the query (`SearchQuery` prompt), the image is the document (no prefix, per the model card). "
           "Embeddings are L2-normalized, so similarity = cosine."),
        code("def enc(x, **kw):\n"
             "    with torch.no_grad():\n"
             "        e = model.encode(x, normalize_embeddings=True, convert_to_tensor=True, **kw)\n"
             "    assert not torch.isnan(e).any(), 'NaN embeddings'\n"
             "    return e\n\n"
             "results = {}\n"
             "for im in IMAGES:\n"
             "    e_img = enc({'image': Image.open(im['path']).convert('RGB')})\n"
             "    e_txt = enc(im['texts'], prompt_name='SearchQuery')\n"
             "    sims = model.similarity(e_txt, e_img.reshape(1, -1)).squeeze(1).tolist()\n"
             "    results[im['name']] = report(im['name'], im['texts'], im['expected'], sims)\n"
             "summarize(results)"),
    ]
    write_notebook(OUT, cells)
    print(f"{sum(1 for i in images if i['url'])}/{len(images)} images via imgbb URL")


if __name__ == "__main__":
    main()
